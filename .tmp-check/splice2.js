const fs = require('fs');
const p = 'public/index.html';
let html = fs.readFileSync(p, 'utf8');
const ui = fs.readFileSync('.tmp-check/ui.js', 'utf8');
const start = '  // ─── 4. UI, LOBBY & MOVEMENT CONTROLS ───';
const end = '  // ─── 5. MULTIPLAYER SOCKET EVENTS ───';
const a = html.indexOf(start);
const b = html.indexOf(end, a + 1);
if (a < 0 || b < 0) throw new Error('markers not found ' + a + ' ' + b);
html = html.slice(0, a) + ui + '\n' + html.slice(b);
fs.writeFileSync(p, html);
console.log('section 4 replaced;', html.length, 'bytes');
